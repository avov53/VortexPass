import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { pathToFileURL } from 'node:url';
const output = new URL('./qa/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1382, height: 908 } });
const errors = [], external = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:5174/') && !r.url().startsWith('data:')) external.push(r.url()); });
const shot = name => page.screenshot({ path: fileURLToPath(new URL(name, output)) });
const nav = name => page.getByRole('button', { name, exact: true }).first().click();
try {
  await page.goto('http://127.0.0.1:5174/');
  await page.getByRole('heading', { name: 'Подключение', exact: true }).waitFor();
  await page.waitForTimeout(180);
  await shot('home.png');
  assert.equal(await page.locator('.rail').evaluate(e => Math.round(e.getBoundingClientRect().width)), 64);
  assert.equal(await page.locator('.navigation').count(), 0);
  const slider = page.getByRole('slider', { name: 'Уровень настройки' });
  await slider.focus();
  await slider.press('ArrowRight');
  assert.equal(await slider.getAttribute('aria-valuenow'), '3');
  assert.equal(await page.locator('.level-slider').evaluate(e => getComputedStyle(e).getPropertyValue('--slider-color').trim()), '#ed923f');
  const box = await slider.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width - 20, box.y + box.height / 2, { steps: 15 });
  await page.mouse.up();
  assert.equal(await slider.getAttribute('aria-valuenow'), '5');
  assert.equal(await page.locator('.level-slider').evaluate(e => getComputedStyle(e).getPropertyValue('--slider-color').trim()), '#a974ed');
  await page.screenshot({ path: fileURLToPath(new URL('./qa/slider-max.png', import.meta.url)) });
  await page.getByRole('button', { name: 'Подключить', exact: true }).click();
  await page.getByRole('heading', { name: 'Соединение активно', exact: true }).waitFor();
  await nav('Профили');
  const youtube = page.locator('.service-card').filter({ hasText: 'YouTube' });
  await youtube.click();
  assert.equal(await youtube.getAttribute('aria-pressed'), 'false');
  const game = page.getByRole('switch', { name: 'Roblox', exact: true });
  await game.click();
  assert.equal(await game.getAttribute('aria-checked'), 'false');
  await nav('Cloudflare WARP');
  const warp = page.getByRole('switch', { name: 'Cloudflare WARP', exact: true });
  await warp.click();
  assert.equal(await warp.getAttribute('aria-checked'), 'true');
  await nav('Журнал');
  assert.equal(await page.locator('.log-row').count(), 2);
  await page.getByRole('button', { name: 'Очистить', exact: true }).click();
  await page.getByRole('heading', { name: 'Пока нет событий', exact: true }).waitFor();
  await nav('Настройки');
  await page.waitForTimeout(180);
  await shot('settings.png');
  const tray = page.getByRole('switch', { name: 'Сворачивать в трей', exact: true });
  await tray.click();
  assert.equal(await tray.getAttribute('aria-checked'), 'false');
  await page.getByRole('button', { name: 'Внешний вид', exact: true }).click();
  await page.getByRole('switch', { name: 'Светлая тема', exact: true }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await page.waitForTimeout(220);
  await shot('light.png');
  await page.getByRole('switch', { name: 'Светлая тема', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await shot('mobile.png');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.page-content').evaluate(e => getComputedStyle(e).animationName), 'none');
  await page.setViewportSize({ width: 1382, height: 908 });
  await page.getByRole('button', { name: 'Профили', exact: true }).first().hover();
  await page.waitForTimeout(550);
  await page.getByRole('tooltip').waitFor();
  await shot('tooltip.png');
  await page.getByRole('button', { name: 'Совместимость', exact: true }).click();
  const mobile = page.getByRole('switch', { name: 'Мобильная совместимость', exact: true });
  await mobile.click();
  assert.equal(await mobile.getAttribute('aria-checked'), 'true');
  await page.getByRole('button', { name: 'Общие', exact: true }).click();
  const startup = page.getByRole('switch', { name: 'Запускать с Windows', exact: true });
  await startup.click();
  assert.equal(await startup.getAttribute('aria-checked'), 'true');
  await nav('Подключение');
  await page.getByRole('button', { name: 'Дополнительные действия', exact: true }).click();
  await page.getByRole('button', { name: 'Новое подключение', exact: true }).click();
  await page.getByRole('button', { name: 'Подключить', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Выберите хотя бы один профиль' }).waitFor();
  await page.locator('.service-card').filter({ hasText: 'YouTube' }).click();
  await page.getByRole('button', { name: 'Автоподбор', exact: true }).click();
  assert.equal(await page.getByRole('slider', { name: 'Уровень настройки' }).getAttribute('aria-valuenow'), '2');
  await page.getByRole('button', { name: 'Подключить', exact: true }).click();
  await page.getByRole('button', { name: 'Отключить', exact: true }).click();
  await page.getByRole('heading', { name: 'Готов к подключению', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  console.log('PASS: profiles, levels, connection, games, WARP, logs, settings, theme, slider drag/colors, mobile, keyboard, reduced motion; no page errors or external requests.');
  const filePage = await browser.newPage({ viewport: { width: 1382, height: 908 } });
  const fileErrors = [];
  filePage.on('pageerror', e => fileErrors.push(e.message));
  await filePage.goto(pathToFileURL(fileURLToPath(new URL('./index.html', import.meta.url))).href);
  await filePage.getByRole('heading', { name: 'Подключение', exact: true }).waitFor();
  assert.match(filePage.url(), /standalone\.html$/);
  await filePage.screenshot({ path: fileURLToPath(new URL('./qa/file-open.png', import.meta.url)) });
  assert.deepEqual(fileErrors, []);
  const standalone = await browser.newPage({ viewport: { width: 1382, height: 908 } });
  await standalone.goto(pathToFileURL(fileURLToPath(new URL('./standalone.html', import.meta.url))).href);
  await standalone.getByRole('heading', { name: 'Подключение', exact: true }).waitFor();
  console.log('PASS: index.html opens standalone.html with file://; the bundled page also opens directly without a server.');
} finally { await browser.close(); }
