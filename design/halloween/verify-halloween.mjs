import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const out=new URL('./qa/',import.meta.url);await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1382,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(new URL('./standalone.html',import.meta.url).href);
await page.getByRole('heading',{name:'Подключение',exact:true}).waitFor();
await page.screenshot({path:fileURLToPath(new URL('home.png',out))});
await page.getByRole('button',{name:'Профили',exact:true}).first().click();
await page.getByRole('button',{name:'Создать профиль',exact:true}).click();
await page.screenshot({path:fileURLToPath(new URL('editor.png',out))});
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Настройки',exact:true}).first().click();
await page.getByRole('button',{name:'Внешний вид',exact:true}).click();
await page.getByRole('switch',{name:'Светлая тема',exact:true}).click();
await page.screenshot({path:fileURLToPath(new URL('light.png',out))});
await page.getByRole('button',{name:'Подключение',exact:true}).first().click();
await page.setViewportSize({width:390,height:844});await page.screenshot({path:fileURLToPath(new URL('mobile-light.png',out))});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
console.log(JSON.stringify({errors,overflow}));await browser.close();if(errors.length||overflow)process.exitCode=1;
